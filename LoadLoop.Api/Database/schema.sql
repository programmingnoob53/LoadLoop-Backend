CREATE TABLE USER_TABLE(
	USER_ID INT IDENTITY(1, 1),
	USER_EMAIL VARCHAR(50) NOT NULL UNIQUE,
	USER_PASSWORD_HASH VARCHAR(MAX) NOT NULL,
	USER_AGE INT NOT NULL CHECK(USER_AGE BETWEEN 18 AND 55),
	USER_ROLE CHAR(1) NOT NULL CHECK(USER_ROLE IN ('A', 'T', 'U')), --A = ADMIN, T = TRANSPORT PROVIDER, U = NORMAL USER
	PRIMARY KEY(USER_ID) 
);

CREATE TABLE TRUCK(
	TRUCK_ID INT IDENTITY(1, 1) PRIMARY KEY,
	TRUCK_IMAGE VARCHAR(MAX) NOT NULL,
	TRUCK_LICENSE_PLATE VARCHAR(10),
	USER_ID INT NOT NULL REFERENCES USER_TABLE(USER_ID),
);


-- in USER_TABLE
ALTER TABLE USER_TABLE ADD CONSTRAINT UQ_USER_EMAIL_ROLE UNIQUE (USER_EMAIL, USER_ROLE); --One role one user

-- in TRUCK
ALTER TABLE TRUCK ADD OWNER_ROLE CHAR(1) NOT NULL DEFAULT 'T' CHECK (OWNER_ROLE = 'T');--only a truck driver owns a truck

