IF DB_ID('LoadLoop') IS NULL BEGIN
CREATE DATABASE LoadLoop;
END

USE LoadLoop;
GO

--FOR THE ADMIN AND USER
CREATE TABLE USER_TABLE(
	US_ID INT IDENTITY(1, 1),
	US_ID_NUMBER CHAR(11) NOT NULL,
	US_EMAIL VARCHAR(50) NOT NULL UNIQUE,--AN ADMIN WILL BE GIVEN THE COMPANY EMAIL
	US_NAME VARCHAR(50) NOT NULL,
	US_SURNAME VARCHAR(50) NOT NULL,
	US_PHONE CHAR(10) NOT NULL UNIQUE,
	US_ROLE CHAR(1) DEFAULT 'U' CHECK(US_ROLE IN('U', 'A', 'D')),
	UNIQUE(US_ID_NUMBER, US_NAME),
	PRIMARY KEY(US_ID)
);
GO

CREATE TABLE DRIVER_TABLE(
	DRI_ID INT IDENTITY(1, 1),
	DRI_SALARY MONEY NOT NULL CHECK(DRI_SALARY >= 9000),
	IS_AVAILABLE BIT NOT NULL DEFAULT 0, --0 => NO 1 => YES
	US_ID INT NOT NULL,
	PRIMARY KEY(DRI_ID),
	FOREIGN KEY(US_ID) REFERENCES USER_TABLE(US_ID)
);
GO

CREATE TABLE ADMIN_TABLE(
	AD_ID INT IDENTITY,
	US_ID INT NOT NULL,
	AD_SALARY MONEY NOT NULL CHECK(AD_SALARY >15000),
	PRIMARY KEY(AD_ID),
	FOREIGN KEY(US_ID) REFERENCES USER_TABLE(US_ID)
);
GO

CREATE TABLE TRUCK_TABLE(
	TRU_ID INT IDENTITY(1, 1),
	DRI_ID INT NOT NULL,
	TRU_TYPE VARCHAR(12) NOT NULL,
	TRU_MAX_WEIGHT INT NOT NULL CHECK(TRU_MAX_WEIGHT >= 1000),
	TRU_LICENSE_PLATE CHAR(7) NOT NULL UNIQUE,
	PRIMARY KEY(TRU_ID),
	FOREIGN KEY(DRI_ID) REFERENCES DRIVER_TABLE(DRI_ID)
);
GO
